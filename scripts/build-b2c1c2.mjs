const oldCount = Math.ceil((idx.count - newEntries.length) / chunk);
const oldAll = [];
for (let n = 0; n < oldCount; n++) {
  const arr = JSON.parse(fs.readFileSync(`${ROOT}/entries/${n}.json`, "utf8"));
  oldAll.push(...arr);
}
